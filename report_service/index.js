
require("dotenv").config({
  path: require("node:path").resolve(__dirname, "../.env"),
});

const express = require("express");
const PDFDocument = require("pdfkit");

const app = express();
app.disable("x-powered-by");
app.use(express.json({ limit: "100kb" }));

const PORT = Number(process.env.REPORT_PORT || 3001);
const REPORT_API_TOKEN = process.env.REPORT_API_TOKEN;

if (!REPORT_API_TOKEN) {
  throw new Error(
    "REPORT_API_TOKEN is missing. Configure it in the root .env file."
  );
}

const MAX_TEXT = 12000;
const MAX_ITEMS = 30;

function cleanText(value, maxLength = MAX_TEXT) {
  if (typeof value !== "string") return "";
  return value.trim().slice(0, maxLength);
}

function cleanList(value) {
  if (!Array.isArray(value)) return [];
  return value
    .slice(0, MAX_ITEMS)
    .map((item) => cleanText(String(item), 1500))
    .filter(Boolean);
}

function authenticate(req, res, next) {
  const header = req.headers.authorization || "";
  const [scheme, token] = header.split(" ");

  if (
    scheme !== "Bearer" ||
    !token ||
    token.length !== REPORT_API_TOKEN.length
  ) {
    return res.status(401).json({ detail: "Unauthorized" });
  }

  const crypto = require("node:crypto");
  const expected = Buffer.from(REPORT_API_TOKEN);
  const received = Buffer.from(token);

  if (!crypto.timingSafeEqual(expected, received)) {
    return res.status(401).json({ detail: "Unauthorized" });
  }

  next();
}

app.get("/health", (_req, res) => {
  res.json({
    status: "ok",
    service: "opspilot-report-service",
  });
});

app.post("/reports", authenticate, (req, res) => {
  const incident = cleanText(req.body.incident, 4000);
  const summary = cleanText(req.body.summary, 6000);
  const severity = cleanText(req.body.severity, 50) || "Unknown";
  const confidence = cleanText(req.body.confidence, 50) || "Not specified";
  const model = cleanText(req.body.model, 150) || "Not specified";
  const evidence = cleanList(req.body.evidence);
  const recommendations = cleanList(req.body.recommendations);

  if (!incident || !summary) {
    return res.status(400).json({
      detail: "Both incident and summary are required.",
    });
  }

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader(
    "Content-Disposition",
    'attachment; filename="opspilot-incident-report.pdf"'
  );
  res.setHeader("Cache-Control", "no-store");

  const pdf = new PDFDocument({
    size: "A4",
    margins: { top: 55, bottom: 55, left: 55, right: 55 },
    info: {
      Title: "OpsPilot AI Incident Report",
      Author: "OpsPilot AI",
      Subject: "IT incident diagnosis",
    },
  });

  pdf.on("error", (error) => {
    console.error("PDF generation error:", error.message);
    if (!res.headersSent) {
      res.status(500).json({ detail: "PDF generation failed." });
    } else {
      res.destroy(error);
    }
  });

  pdf.pipe(res);

  pdf
    .font("Helvetica-Bold")
    .fontSize(24)
    .fillColor("#006c49")
    .text("OpsPilot AI", { align: "left" });

  pdf
    .moveDown(0.3)
    .font("Helvetica")
    .fontSize(11)
    .fillColor("#475569")
    .text("IT INCIDENT DIAGNOSTIC REPORT");

  pdf.moveDown(1);
  pdf.moveTo(55, pdf.y).lineTo(540, pdf.y).strokeColor("#10b981").stroke();
  pdf.moveDown(1);

  function section(title, body) {
    pdf
      .moveDown(0.5)
      .font("Helvetica-Bold")
      .fontSize(13)
      .fillColor("#006c49")
      .text(title);

    pdf
      .moveDown(0.25)
      .font("Helvetica")
      .fontSize(10)
      .fillColor("#172033")
      .text(body || "Not provided", {
        lineGap: 3,
        paragraphGap: 4,
      });
  }

  section("Incident", incident);
  section("AI Summary", summary);
  section("Severity", severity);
  section("Confidence", confidence);
  section("Model", model);

  section(
    "Evidence",
    evidence.length
      ? evidence.map((item, i) => `${i + 1}. ${item}`).join("\n")
      : "No evidence provided."
  );

  section(
    "Recommendations",
    recommendations.length
      ? recommendations.map((item, i) => `${i + 1}. ${item}`).join("\n")
      : "No recommendations provided."
  );

  pdf.moveDown(1);
  pdf
    .fontSize(8)
    .fillColor("#64748b")
    .text(
      "Generated by OpsPilot AI. Validate recommendations before applying changes to production systems.",
      { align: "left" }
    );

  pdf.end();
});

app.listen(PORT, "0.0.0.0", () => {
  console.log(`OpsPilot report service listening on port ${PORT}`);
});
